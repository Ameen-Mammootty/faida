def group_by_category(items: Sequence[dict]) -> list[dict]:
    """Menu items grouped by the menu's own category for the screen (D6):
    categories in alphabetical order, `Other` last for the items with none,
    the items in the order given. Each item dict is passed through untouched
    and read for its `category`."""
    groups: dict[str, list[dict]] = {}
    for item in items:
        groups.setdefault(item.get("category") or OTHER_CATEGORY, []).append(item)
    named = sorted(name for name in groups if name != OTHER_CATEGORY)
    if OTHER_CATEGORY in groups:
        named.append(OTHER_CATEGORY)
    return [
        {"category": name, "guidance": PUSH_GUIDANCE_WORDS, "items": groups[name]} for name in named
    ]
