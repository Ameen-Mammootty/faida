def push_week_json(
    week: PushWeek,
    *,
    today: datetime.date,
    kept: Mapping[str, Decimal | None],
    currency: str,
) -> dict:
    """A push week as the screen shows it: its dates, whether it is frozen
    and why, and its list grouped by the menu's own category."""
    frozen = frozen_week_sentence(week.window, today)
    items = [
        push_item_json(item, kept_per_plate=kept.get(item.menu_item_id), currency=currency)
        for item in week.items
    ]
    return {
        "id": week.push_week_id,
        **_window_json(week.window),
        "frozen": frozen is not None,
        "frozen_words": frozen,
        "items": items,
        "categories": group_by_category(items),
    }


