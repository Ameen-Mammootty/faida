# --- the calendar ---------------------------------------------------------------


def month_start(day: datetime.date) -> datetime.date:
    return day.replace(day=1)


def month_end(month: datetime.date) -> datetime.date:
    first = month_start(month)
    return first.replace(day=calendar.monthrange(first.year, first.month)[1])


def days_in_month(month: datetime.date) -> int:
    first = month_start(month)
    return calendar.monthrange(first.year, first.month)[1]


def month_words(month: datetime.date) -> str:
    """ "September 2026" - the scheme month as the owner names it."""
    return f"{month.strftime('%B')} {month.year}"


def month_key(month: datetime.date) -> str:
    """ "2026-09" - the month on the wire and in a URL."""
    return f"{month.year:04d}-{month.month:02d}"


def parse_month_key(key: str) -> datetime.date | None:
    """ "2026-09" to its first day, or None for anything else."""
    try:
        year, month = key.split("-")
        return datetime.date(int(year), int(month), 1)
    except (ValueError, AttributeError):
        return None


def push_weeks(month: datetime.date) -> tuple[Window, ...]:
    """Monday to Sunday, clipped to the month (D5): the first and last week
    may be short, and no statement ever waits for another month's days. A
    month starting on a Wednesday gets a first week of five days; a 31-day
    month starting on a Monday gets five weeks."""
    first, last = month_start(month), month_end(month)
    weeks = []
    cursor = first
    while cursor <= last:
        sunday = cursor + datetime.timedelta(days=6 - cursor.weekday())
        end = min(sunday, last)
        weeks.append(Window(cursor, end))
        cursor = end + datetime.timedelta(days=1)
    return tuple(weeks)


def week_started(window: Window, today: datetime.date) -> bool:
    """A week whose start date is today or earlier is under way and frozen
    (D5); one starting tomorrow or later may still be re-aimed."""
    return window.start <= today


def week_words(window: Window) -> str:
    """ "7-13 Sep", or "28 Sep-4 Oct" across a month end."""
    return window_words(window)


# --- validation the doors share ---------------------------------------------------


def shares_problem(
    manager: Decimal | None, supervisor: Decimal | None, sales: Decimal | None
) -> str | None:
    """The refusal sentence for a set of role shares, or None when they are
    three percentages summing to one hundred (D2).

    Two decimals at most, because that is what a share is stored as
    (`numeric(5,2)`): a third decimal would be rounded away on the way in, and
    three shares that summed to a hundred before the rounding need not sum to
    a hundred after it - which the table's own check would then refuse, in
    SQL, long past the door that should have said so in words.
    """
    for name, value in (("manager", manager), ("supervisor", supervisor), ("sales team", sales)):
        if value is None:
            return f"the {name} share is missing: three percentages summing to 100 are needed"
        if value < 0:
            return f"the {name} share cannot be negative"
        if value.as_tuple().exponent < -2:
            return (
                f"the {name} share is written to more decimals than a share is kept to: "
                "two at most, like 33.33"
            )
    if manager + supervisor + sales != _HUNDRED:
        return (
            f"the three shares sum to {_pct_plain(manager + supervisor + sales)}%, not 100%: "
            "the manager, the supervisor and the sales team must share the whole pool"
        )
    return None


def targets_problem(
    net_sales_target: Decimal | None, above_target_pct: Decimal | None, cap: Decimal | None
) -> str | None:
    """The refusal sentence for one branch's targets, or None. The branch is
    named by `branch_targets_problem`, which is the only caller: these say
    what is wrong with a figure, never which box it came from."""
    if net_sales_target is None:
        return "a net sales target is needed"
    if net_sales_target < 0:
        return "a net sales target cannot be negative"
    if above_target_pct is None:
        return "the percentage of net sales above target is needed"
    if above_target_pct < 0 or above_target_pct > _HUNDRED:
        return "the percentage of net sales above target must be between 0 and 100"
    if cap is not None and cap < 0:
        return "a cap cannot be negative; leave it blank for no cap"
    return None


#: The one refusal when no shares have been set yet: a scheme month is
#: created *with* the shares in force, so there is nothing to snapshot (D2,
#: D4). Worded here because the door that refuses it and the screen that
#: prevents it must say the same thing.
SHARES_NOT_SET = (
    "the role shares are not set: a scheme month is created with the shares in force that day, "
    "so set the three shares first"
)


def month_taken_sentence(month: datetime.date) -> str:
    """Why a second scheme month for the same calendar month is refused (D4):
    the first one was frozen when it was created, and a second would be a
    second set of rules for one month."""
    return (
        f"{month_words(month)} already has a scheme month: it was frozen when it was created, "
        "so its targets cannot be set a second time"
    )


@dataclass(frozen=True)
class TypedTarget:
    """What the owner typed into one branch's three boxes on the create form,
    before it is known to be a target: any of the three may be missing, and
    the cap is blank for no cap. `BranchTargets` is the same figures once
    they are a target - stored, frozen and scored on."""

    branch_id: str
    net_sales_target: Decimal | None
    above_target_pct: Decimal | None
    cap: Decimal | None


def branch_targets_problem(
    branch_names: Mapping[str, str], targets: Sequence[TypedTarget]
) -> str | None:
    """The refusal sentence for a whole month's branch targets, or None (D3).

    Every branch of the chain gets exactly one target and no branch outside it
    gets any, because a scheme month scores every branch and a branch the
    owner did not type a figure for would be scored against nothing. Each
    target is then checked by `targets_problem` and named by the branch whose
    box it came from, so an owner looking at three boxes is told which one.
    """
    seen: list[str] = []
    for target in targets:
        name = branch_names.get(target.branch_id)
        if name is None:
            return "a target was sent for a branch that is not in this chain"
        if target.branch_id in seen:
            return f"{name} was sent two targets; every branch gets one"
        seen.append(target.branch_id)
        problem = targets_problem(target.net_sales_target, target.above_target_pct, target.cap)
        if problem is not None:
            return f"{name}: {problem}"
    missing = [name for branch_id, name in branch_names.items() if branch_id not in seen]
    if missing:
        return (
            f"{_list_words(missing)} {'has' if len(missing) == 1 else 'have'} no target: "
            "every branch of the chain needs one for the month"
        )
    return None


def _list_words(names: Sequence[str]) -> str:
    """ "Deira", "Deira and Karama", "Deira, Karama and Al Quoz"."""
    if len(names) == 1:
        return names[0]
    return f"{', '.join(names[:-1])} and {names[-1]}"


def frozen_week_sentence(window: Window, today: datetime.date) -> str | None:
    """Why a push list cannot be set on this week, or None when it can (D5)."""
    if not week_started(window, today):
        return None
    if window.end < today:
        return f"the week of {week_words(window)} has ended and is frozen"
    return f"the week of {week_words(window)} has started and is frozen"


def push_item_problem(name: str, *, archived: bool, mapped: bool) -> str | None:
    """Why a menu item cannot be a push item, or None (D7)."""
    if archived:
        return f"{name} is archived from the menu and cannot be pushed"
    if not mapped:
        return (
            f"{name} has no till name mapped to it, so it could only ever score zero; "
            "map a till name to it on the Sales screen first"
        )
    return None


def hole_sentence(name: str, *, archived: bool, mapped: bool) -> str | None:
    """Why a push item on a list cannot be counted now, or None (D7): the
    mapping was removed or the dish archived after the list was set."""
    if archived:
        return f"{name} cannot be counted: it was archived from the menu"
    if not mapped:
        return f"{name} cannot be counted: no till name is mapped to it"
    return None


