# --- words ----------------------------------------------------------------------


def _pct_plain(value: Decimal) -> str:
    """ "10" for 10.00, "12.5" for 12.50."""
    normalized = value.normalize()
    if normalized == normalized.to_integral_value():
        return str(int(normalized))
    return f"{normalized:f}"


def _fils(amount: Decimal) -> Decimal:
    return amount.quantize(FILS, rounding=ROUND_HALF_UP)


def _whole(amount: Decimal) -> Decimal:
    return amount.quantize(_WHOLE, rounding=ROUND_HALF_UP)


def kept_words(margin: Decimal | None, currency: str) -> str:
    """What a plate keeps after ingredients, fils-precise, beside the rate
    box - or the honest word for a dish that is not costed (D7, D8)."""
    if margin is None:
        return "not costed"
    return f"keeps {_price_words(margin, currency)} per plate"


def previous_month_words(net_sales: Decimal | None, currency: str) -> str:
    """Last month's net sales beside the target box, as advice and never as
    the baseline (D3)."""
    if net_sales is None:
        return "no sales loaded last month"
    return f"{_money_words(net_sales, currency)} last month"


def target_words(portions: Decimal, target: Decimal) -> str:
    return f"{_portions_words(portions)} of {_portions_words(target)} portions"


def status_words(status: str, days_loaded: int, days_in_month: int, *, differs: bool) -> str:
    if status == FINAL:
        return f"{FINAL}; {TILL_NOW_SAYS_OTHERWISE}" if differs else FINAL
    return f"{PROVISIONAL}, {days_loaded} of {days_in_month} days loaded"


# --- the arithmetic -------------------------------------------------------------


def _portions_for(
    item: PushItem, window: Window, branch_id: str, days: Iterable[ItemDay]
) -> tuple[Decimal, int]:
    total = Decimal(0)
    uncounted = 0
    for day in days:
        if day.branch_id != branch_id or day.menu_item_id != item.menu_item_id:
            continue
        if not (window.start <= day.business_date <= window.end):
            continue
        total += day.qty_net
        uncounted += day.no_qty_lines
    return total.quantize(_PORTION, rounding=ROUND_HALF_UP), uncounted


def score_item(
    item: PushItem, window: Window, branch_id: str, days: Iterable[ItemDay]
) -> ItemScore:
    target = item.targets.get(branch_id, Decimal(0)).quantize(_PORTION)
    hole = hole_sentence(item.name, archived=item.archived, mapped=item.mapped)
    if hole is not None:
        return ItemScore(
            push_item_id=item.push_item_id,
            menu_item_id=item.menu_item_id,
            name=item.name,
            category=item.category,
            rate_per_portion=_fils(item.rate_per_portion),
            portion_target=target,
            portions=None,
            portions_above=Decimal(0),
            earned=Decimal("0.00"),
            hole=hole,
            no_qty_lines=0,
            words=hole,
        )
    portions, uncounted = _portions_for(item, window, branch_id, days)
    above = max(Decimal(0), portions - target)
    earned = _fils(above * item.rate_per_portion)
    return ItemScore(
        push_item_id=item.push_item_id,
        menu_item_id=item.menu_item_id,
        name=item.name,
        category=item.category,
        rate_per_portion=_fils(item.rate_per_portion),
        portion_target=target,
        portions=portions,
        portions_above=above,
        earned=earned,
        hole=None,
        no_qty_lines=uncounted,
        words=target_words(portions, target),
    )


def score_week(week: PushWeek, branch_id: str, days: Iterable[ItemDay]) -> WeekScore:
    items = tuple(score_item(item, week.window, branch_id, days) for item in week.items)
    earned = sum((item.earned for item in items), Decimal("0.00"))
    return WeekScore(
        push_week_id=week.push_week_id,
        window=week.window,
        items=items,
        earned=earned,
        empty=not items,
        words=NO_PUSH_LIST if not items else f"{len(items)} on the list",
    )


def split_pool(pool: Decimal, shares: Shares) -> Split:
    """pool × each share to the fil, the remainder to the sales share, so the
    three sum to the pool exactly (D2)."""
    manager = _fils(pool * shares.manager_pct / _HUNDRED)
    supervisor = _fils(pool * shares.supervisor_pct / _HUNDRED)
    sales = _fils(pool) - manager - supervisor
    return Split(shares=shares, manager=manager, supervisor=supervisor, sales=sales)


def compute_figures(
    scheme: SchemeMonth,
    branch_id: str,
    *,
    days: Sequence[LoadedDay],
    items: Sequence[ItemDay],
    currency: str,
) -> Figures:
    """One branch's figures for the scheme month from its loaded days (D8)."""
    targets = scheme.targets.get(branch_id)
    if targets is None:
        raise ValueError(f"branch {branch_id} has no targets in scheme month {scheme.month}")
    first, last = month_start(scheme.month), month_end(scheme.month)
    loaded = [d for d in days if d.branch_id == branch_id and first <= d.business_date <= last]
    days_loaded = len({d.business_date for d in loaded})
    net_sales = _fils(sum((d.net_sales for d in loaded), Decimal(0)))
    net_above = max(Decimal(0), net_sales - targets.net_sales_target)
    net_earned = _fils(net_above * targets.above_target_pct / _HUNDRED)

    weeks = tuple(score_week(week, branch_id, items) for week in scheme.weeks)
    items_earned = sum((week.earned for week in weeks), Decimal("0.00"))
    before_cap = _fils(items_earned + net_earned)
    cap = None if targets.cap is None else _fils(targets.cap)
    capped = cap is not None and before_cap > cap
    exact = cap if capped else before_cap
    if days_loaded == 0:
        pool: Decimal | None = None
        rounded: Decimal | None = None
        split: Split | None = None
        pool_words = NO_POOL_WORDS
    else:
        pool = exact
        rounded = _whole(exact)
        split = split_pool(exact, scheme.shares)
        pool_words = _money_words(exact, currency)
    return Figures(
        days_loaded=days_loaded,
        days_in_month=days_in_month(scheme.month),
        net_sales=net_sales,
        net_sales_target=_fils(targets.net_sales_target),
        net_above=_fils(net_above),
        above_target_pct=targets.above_target_pct.quantize(_PCT),
        net_earned=net_earned,
        weeks=weeks,
        items_earned=items_earned,
        pool_before_cap=before_cap,
        cap=cap,
        capped=capped,
        pool=pool,
        pool_rounded=rounded,
        split=split,
        net_words=f"{_money_words(net_sales, currency)} of "
        f"{_money_words(targets.net_sales_target, currency)}",
        pool_words=pool_words,
    )


def _notes(figures: Figures, currency: str) -> tuple[str, ...]:
    notes: list[str] = []
    for week in figures.weeks:
        if week.empty:
            notes.append(f"{week_words(week.window)}: {NO_PUSH_LIST}")
            continue
        for item in week.items:
            if item.hole is not None:
                notes.append(f"{week_words(week.window)}: {item.hole}")
            elif item.no_qty_lines:
                lines = "line" if item.no_qty_lines == 1 else "lines"
                notes.append(
                    f"{week_words(week.window)}: {item.no_qty_lines} till {lines} for "
                    f"{item.name} carried no quantity and are not counted"
                )
    if figures.capped and figures.cap is not None:
        notes.append(
            f"capped at {_money_words(figures.cap, currency)}; "
            f"{_money_words(figures.pool_before_cap, currency)} earned before the cap"
        )
    return tuple(notes)


def compose_statement(
    scheme: SchemeMonth,
    branch_id: str,
    *,
    days: Sequence[LoadedDay],
    items: Sequence[ItemDay],
    newest_loaded: datetime.date | None,
    approval: Approval | None,
    currency: str,
) -> Statement:
    """One branch's statement for one scheme month, derived on every read
    from the sales days and stored nowhere (D10, D11, D12).

    Provisional until every calendar day is loaded; final once approved, and
    then the figures are the approved snapshot - what was paid - with the
    live figures beside them and the note when the till now says otherwise.
    """
    live = compute_figures(scheme, branch_id, days=days, items=items, currency=currency)
    if approval is None:
        return Statement(
            branch_id=branch_id,
            month=month_start(scheme.month),
            newest_loaded=newest_loaded,
            status=PROVISIONAL,
            status_words=status_words(
                PROVISIONAL, live.days_loaded, live.days_in_month, differs=False
            ),
            figures=live,
            approval=None,
            till_now_says_otherwise=False,
            recomputed=None,
            notes=_notes(live, currency),
        )
    approved = figures_from_json(approval.figures)
    differs = figures_json(live) != approval.figures
    notes = list(_notes(approved, currency))
    if differs:
        notes.append(
            f"{TILL_NOW_SAYS_OTHERWISE}: a sales day was replaced after approval; the approved "
            f"figures stand and the recomputed ones are beside them"
        )
    return Statement(
        branch_id=branch_id,
        month=month_start(scheme.month),
        newest_loaded=newest_loaded,
        status=FINAL,
        status_words=status_words(
            FINAL, approved.days_loaded, approved.days_in_month, differs=differs
        ),
        figures=approved,
        approval=approval,
        till_now_says_otherwise=differs,
        recomputed=live if differs else None,
        notes=tuple(notes),
    )


def approvable(figures: Figures) -> str | None:
    """Why a statement cannot be approved, or None (D10): every calendar day
    of the month must be loaded for the branch."""
    if figures.days_loaded < figures.days_in_month:
        return (
            f"the month is provisional, {figures.days_loaded} of {figures.days_in_month} days "
            "loaded: load every day before approving"
        )
    return None


def week_in_view(scheme: SchemeMonth, day: datetime.date) -> PushWeek | None:
    """The push week that holds `day`, or None when the day is outside the
    month."""
    for week in scheme.weeks:
        if week.window.start <= day <= week.window.end:
            return week
    return None


def sentences(statement: Statement) -> list[str]:
    """Every composed sentence on a statement, for the banned-words test."""
    out = [statement.status_words, *statement.notes]
    for figures in (statement.figures, statement.recomputed):
        if figures is None:
            continue
        out += [figures.net_words, figures.pool_words]
        for week in figures.weeks:
            out.append(week.words)
            out += [item.words for item in week.items]
    return out


