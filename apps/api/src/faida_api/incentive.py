"""M13 WP-131: the staff incentive, pure - the calendar rules, every figure
and every sentence of a branch's statement, and the wire shapes the screen
and the scoreboard read (plan.md §8 M13, D1 to D18; `CONTEXT.md` for the
words; `Docs/adr/0001` for what is scored on; issue #6 for the arithmetic).

The vocabulary is the glossary's: a **scheme month** is a calendar month,
frozen when created; a **push week** is Monday to Sunday clipped to it; a
**push list** is the push items of one week, each a menu item with a rate
per portion above target and a portion **target** per branch; the **pool** is
what a branch's team has earned for the month, split by the **role shares**
snapshotted when the month was created; the **statement** is the month's
scores and pool as read from the loaded sales days, provisional until every
day is loaded and final once the owner approves it; the staff-facing word is
**bonus**, and never profit share or commission.

Pure by design, in `signals.py`'s and `usage.py`'s shape: no clock, no
database, no HTTP. The read hands it the scheme month as the rows say it,
the branch's loaded days, the till's item days with their menu item read
through the mapping, and the approval if there is one; it hands back figures
and words. That is what makes every rule testable without a database, and
what lets the screen's fixtures be generated by this module rather than
copied from it (the dashboard's `generate.py` rule).

The arithmetic, here and nowhere else (D8, D9, D10):

- portions for a push item in a push week for a branch are the net signed
  quantity of every sales line whose till item maps to that menu item within
  the week's dates, rounded once per item - a refunded plate is not a sold
  plate (D9, the opposite of M12's P9 for a stated reason);
- a push item whose menu item is archived or whose till items are all
  unmapped is a hole: portions None, named in the notes, contributing
  nothing (D7) - never a zero, which would read as a team that sold none;
- net sales for the month are the sum of the loaded days' net sales;
- pool = Σ max(0, portions − target) × rate + max(0, net sales − net target)
  × percentage, then min(cap) where a cap is set; whole dirhams rounded half
  up as the headline, exact to the fil beneath;
- the split is pool × each role share to the fil, the remainder to the sales
  share, so the three sum to the pool;
- a branch with nothing loaded in the month has no pool - None, never a
  zero pool presented as earned;
- the statement says "provisional, N of M days loaded" until N = M, "final"
  once approved, and carries "the till now says otherwise" beside the
  recomputed figures when a day was replaced after approval (D12).

Money words are `contribution._money_words` (whole dirhams) and
`contribution._price_words` (fils, for a rate and what a plate keeps),
portions `signals._portions_words`, dates `ratio.window_words` - imported and
called, never copied, so a rounding rule can only ever change in one place.
`BANNED_WORDS` is checked by a test that calls this module: no composed
sentence ever says profit, profit share, commission, verified or food cost.
"""

