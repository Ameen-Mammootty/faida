def test_a_chain_of_twelve_branches_still_renders_inside_metas_cap():
    league = [
        _branch(f"b{n}", f"Branch Number {n}", month=f"{n}000.00", contribution_pct="66.7")
        for n in range(1, 13)
    ]
    month = _hand(
        league=league,
        latest=[(f"b{n}", f"{n}00.00") for n in range(1, 13)],
        net_sales="78000.00",
    )
    made = brief.compose(month, month)

    assert len(made.rows) == 12
    assert len(brief.render(made)) < brief.BODY_MAX_CHARS
    assert len(brief.render(made)) == len(brief.render(brief.compose(_shrink(month), month)))


def _shrink(month: dict) -> dict:
    """The same chain with one branch: the five lines do not grow with the
    branch count by design, and the twelve-branch test proves it by measuring
    both renderings."""
    one = json.loads(json.dumps(month))
    one["league"] = one["league"][:1]
    one["latest_day"]["branches"] = one["latest_day"]["branches"][:1]
    return one


