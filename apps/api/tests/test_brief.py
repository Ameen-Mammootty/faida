def test_every_branch_row_carries_the_leagues_own_figures_in_the_leagues_order():
    month = _payload("full")
    made = brief.compose(month, month)
    on_day = {b["branch_id"]: b for b in month["latest_day"]["branches"]}

    assert [row.name for row in made.rows] == [r["branch_name"] for r in month["league"]]
    for row, source in zip(made.rows, month["league"], strict=True):
        assert row.month == D(source["net_sales"]).quantize(D(1))
        assert row.latest_day == D(on_day[source["branch_id"]]["net_sales"]).quantize(D(1))
        assert row.materials_share == str(D(100) - D(source["contribution_pct"]))
        assert row.materials_share_words == f"{row.materials_share}%"
    assert made.rows[-1].name == "Al Quoz"
    assert made.rows[-1].latest_day_words == "4,385"
    assert made.rows[-1].month_words == "30,719"
    assert made.rows[-1].materials_share_words == "30.1%"


def test_a_branch_with_no_sales_on_the_latest_day_shows_a_hole_and_never_a_nought():
    month = _payload("partial")
    made = brief.compose(month, month)
    deira = next(row for row in made.rows if row.name == "Deira")
    deira_id = next(r["branch_id"] for r in month["league"] if r["branch_name"] == "Deira")

    assert deira_id not in {b["branch_id"] for b in month["latest_day"]["branches"]}
    assert next(r for r in month["league"] if r["branch_id"] == deira_id)["net_sales"] is None
    assert deira.latest_day is None and deira.latest_day_words == brief.HOLE
    assert deira.month is None and deira.month_words == brief.HOLE
    assert deira.materials_share is None and deira.materials_share_words == brief.HOLE


