"""M10 WP-100: the morning brief, composed and pinned to its payload
(Docs/M10_DECOMPOSITION.md §3 C15, §3.1, §7; plan.md §7.3 row 100).

No database: `brief.compose` is handed the dashboard read's own JSON, so every
case here is the payload a phone's brief is actually built from. The five
committed mock fixtures are the real arithmetic of the shipped modules
(`apps/web/src/lib/mock/dashboard`, regenerated by `generate.py`), and the
hand-built cases are the shapes those five do not carry - a chain of one, a
chain of twelve, a single rise, a note long enough to break Meta's rule.

Every number in every line is read back out of the same dict the line was
composed from and compared, never retyped: a figure that drifts from its field
is the one failure this file exists to catch. The forbidden words are checked
by rendering the brief and reading the string, never by grepping the module.

Two fields the brief needs - `total.cost` and `total.costed_sales` - are
WP-101's addition to the wire and are not in the committed fixtures yet, so
`_payload` sets them here from the fixture's own costed rows: the material cost
of the costed rows and their net item sales. `test_the_cost_fields_are_the_sums_of_the_costed_rows`
pins those sums to the figures hand-checked in the decomposition (AED 18,342.39
and AED 56,294.45 for `full`) and to the chain's own contribution, so the
stand-in cannot be quietly wrong.
"""

import json
from decimal import Decimal
from pathlib import Path

import pytest

from faida_api import brief
from faida_api.contribution import _money_words, _pct_words

D = Decimal
MOCK = Path(__file__).resolve().parents[3] / "apps" / "web" / "src" / "lib" / "mock" / "dashboard"
FORBIDDEN = ("food cost", "net profit", "verified")


# --- the payloads -----------------------------------------------------------


def _with_cost_fields(data: dict) -> dict:
    """WP-101's two additive fields, stood in from the payload's own item rows
    until that lane lands: the costed rows' material cost and their net item
    sales. A read with nothing costed carries neither, which is the withheld
    case the brief must say in words."""
    rows = [r for r in data["items"]["all"] if r["contribution"] is not None]
    data["total"]["cost"] = str(sum((D(r["cost"]) for r in rows), D(0))) if rows else None
    data["total"]["costed_sales"] = (
        str(sum((D(r["net_item_sales"]) for r in rows), D(0))) if rows else None
    )
    return data


def _payload(name: str, scope: str = "") -> dict:
    return _with_cost_fields(json.loads((MOCK / f"{name}.json").read_text())[scope])


def _branch(
    branch_id: str,
    name: str,
    *,
    month: str | None,
    contribution_pct: str | None,
    window: tuple[str, str] = ("2026-08-25", "2026-08-31"),
) -> dict:
    return {
        "branch_id": branch_id,
        "branch_name": name,
        "window": {"from": window[0], "to": window[1], "days": 7},
        "net_sales": month,
        "contribution_pct": contribution_pct,
        "costed_share_pct": "90.0",
        "contribution_quality": "reliable_with_limitations",
    }


def _item(item_id: str, name: str, contribution: str) -> dict:
    return {
        "menu_item_id": item_id,
        "menu_item_name": name,
        "contribution": contribution,
        "cost": "1.00",
        "net_item_sales": "10.00",
    }


def _hand(
    *,
    league: list[dict],
    latest: list[tuple[str, str]],
    sentence: str = "Sales loaded to Mon 31 Aug, yesterday.",
    freshness_quality: str = "reliable_with_limitations",
    net_sales: str = "10000.00",
    cost: str | None = "3000.00",
    costed_sales: str | None = "9000.00",
    costed_share_pct: str | None = "90.0",
    contribution_pct: str | None = "66.7",
    contribution_quality: str = "reliable_with_limitations",
    contribution_notes: tuple[str, ...] = (),
    top: list[dict] | None = None,
    bottom: list[dict] | None = None,
    all_items: list[dict] | None = None,
    count: int | None = None,
    moves: list[dict] | None = None,
    period_from: str = "2026-08-04",
) -> dict:
    """A dashboard payload by hand, in the route's own shape: only the keys the
    brief reads, so a case says exactly what it is about."""
    top = top or []
    bottom = bottom or []
    return {
        "period": {"from": period_from, "to": "2026-08-31"},
        "freshness": {"sentence": sentence, "quality": freshness_quality},
        "latest_day": {
            "date": "2026-08-31",
            "net_sales": "4000.00",
            "branches": [
                {"branch_id": bid, "branch_name": bid, "net_sales": value} for bid, value in latest
            ],
        },
        "league": league,
        "total": {
            "net_sales": net_sales,
            "cost": cost,
            "costed_sales": costed_sales,
            "costed_share_pct": costed_share_pct,
            "contribution_pct": contribution_pct,
            "contribution_quality": contribution_quality,
            "contribution_notes": list(contribution_notes),
        },
        "items": {
            "top": top,
            "bottom": bottom,
            "all": all_items if all_items is not None else [*top, *bottom],
            "count": count if count is not None else len({i["menu_item_id"] for i in top + bottom}),
        },
        "price_moves": {"count": len(moves or []), "moves": moves or []},
    }


def _move(name: str, money: str | None, *, direction: str = "up") -> dict:
    return {
        "ingredient_name": name,
        "direction": direction,
        "money_at_stake": money,
        "sentence": f"{name} is up AED 1.00 per kg since 21 Aug.",
    }


# --- the five lines, against the committed fixtures --------------------------


def test_the_cost_fields_are_the_sums_of_the_costed_rows():
    """The stand-in for WP-101's two fields is the decomposition's own
    hand-check: 18,342.39 of materials against 56,294.45 of costed sales, whose
    difference is the chain's contribution to the fils."""
    full = _payload("full")
    assert full["total"]["cost"] == "18342.39"
    assert full["total"]["costed_sales"] == "56294.45"
    assert D(full["total"]["costed_sales"]) - D(full["total"]["cost"]) == D(
        full["total"]["contribution"]
    )


def test_the_full_fixture_says_every_figure_the_payload_gives():
    month = _payload("full")
    made = brief.compose(month, month)

    assert not made.quiet
    assert made.day == month["freshness"]["sentence"]
    assert made.latest_day == (
        f"{_money_words(D(month['latest_day']['net_sales']), 'AED')} on Mon 31 Aug"
    )
    assert made.month_to_date == (
        f"{_money_words(D(month['total']['net_sales']), 'AED')} (25-31 Aug loaded)"
    )
    assert made.materials_used == (
        f"{_money_words(D(month['total']['cost']), 'AED')} at the latest prices (estimated)"
    )
    share = D(100) - D(month["total"]["contribution_pct"])
    assert made.materials_share == (
        f"{share}% of the {_money_words(D(month['total']['costed_sales']), 'AED')} costed "
        f"({_pct_words(D(month['total']['costed_share_pct']))} of sales) (estimated)"
    )
    # The shape the founder was shown, to the character.
    assert made.latest_day == "AED 9,493 on Mon 31 Aug"
    assert made.month_to_date == "AED 67,471 (25-31 Aug loaded)"
    assert made.materials_share.startswith("32.6% of the AED 56,294 costed (84% of sales)")


def test_the_materials_share_is_a_hundred_less_the_share_kept():
    for name in ("full", "partial", "quiet"):
        month = _payload(name)
        made = brief.compose(month, month)
        kept = D(month["total"]["contribution_pct"])
        assert made.materials_share.startswith(f"{D(100) - kept}%")
