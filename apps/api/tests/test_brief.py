def test_with_five_or_fewer_costed_items_the_worst_list_is_what_is_left():
    """`items.bottom` is empty until six items are costed, so the worst come
    off the end of the top list - and an item already named among the best is
    never named again among the worst."""
    month = _payload("quiet")
    made = brief.compose(month, month)

    assert month["items"]["bottom"] == []
    assert month["items"]["count"] == 4
    assert [line.name for line in made.earning_most] == [
        r["menu_item_name"] for r in month["items"]["top"][:3]
    ]
    fourth = month["items"]["top"][3]["menu_item_name"]
    assert [line.name for line in made.earning_least] == [fourth]
    assert not {line.name for line in made.earning_most} & {
        line.name for line in made.earning_least
    }


def test_with_exactly_five_costed_items_the_worst_two_are_the_two_the_best_left():
    top = [_item(f"i{n}", f"Item {n}", f"{1000 - n * 100}.00") for n in range(1, 6)]
